"""Eigenvalue solvers of general eigenproblems A x = λ B x (eigenmode studies): dense LAPACK and ARPACK."""
from __future__ import annotations
import numpy as np
from scipy.linalg import eig  # type: ignore
from scipy.sparse import csc_matrix  # type: ignore
from scipy.sparse.linalg import eigs, splu, LinearOperator  # type: ignore
from loguru import logger
from .solver_base import EigSolver, _pfx


############################################################
#                 EIGENMODE FILTER ROUTINE                #
############################################################


def filter_real_modes(
    eigvals: np.ndarray,
    eigvecs: np.ndarray,
    k0: float,
    ermax: complex,
    urmax: complex,
    sign: float,
) -> tuple[np.ndarray, np.ndarray]:
    """Filters eigenmodes that are actually real (removing spurious ones generated by ARPACK)

    Uses the eigen values constrianed by a search space limited by the
    propagation constant.

    Args:
        eigvals (np.ndarray): array of eigenvalues
        eigvecs (np.ndarray): 2D array of eigenvectors
        k0 (float): Propagation constant
        ermax (complex): Maximum epsilon_r
        urmax (complex): maximum mu_r
        sign (float): expected sign before eigenvalue (can be configured externally)

    Returns:
        tuple[np.ndarray, np.ndarray]: A filtered list of unique eigenvalues/vectors
    """
    minimum = 1
    extremum = (k0**2) * ermax * urmax * 2
    eigvals[eigvals == np.inf] = 1e30
    eigvals[eigvals == -np.inf] = -1e30
    mask = (sign * eigvals <= extremum) & (sign * eigvals >= minimum)
    filtered_vals = eigvals[mask]
    filtered_vecs = eigvecs[:, mask]
    k0vals = np.sqrt(sign * filtered_vals)
    order = np.argsort(np.abs(k0vals))  # ascending distance
    filtered_vals = filtered_vals[order]  # reorder eigenvalues
    filtered_vecs = filtered_vecs[:, order]
    return filtered_vals, filtered_vecs


############################################################
#                 DIRECT EIGENMODE SOLVERS                #
############################################################


class SolverLAPACK(EigSolver):
    name = "LAPACK"

    def eig(
        self,
        A: csc_matrix,
        B: csc_matrix,
        nmodes: int = 6,
        target_k0: float = 0,
        which: str = "LM",
        sign: float = 1.0,
    ) -> tuple[np.ndarray, np.ndarray]:
        """
        Dense solver for  A x = λ B x   with A = Aᴴ, B = Bᴴ (B may be indefinite).

        Parameters
        ----------
        A, B : (n, n) array_like, complex127/complex64/float64
        k    : int or None
            How many eigenpairs to return.
            * None  → return all n
            * k>0   → return k pairs with |λ| smallest

        Returns
        -------
        lam  : (m,) real ndarray      eigenvalues  (m = n or k)
        vecs : (n, m) complex ndarray eigenvectors, B-orthonormal  (xiᴴ B xj = δij)
        """
        logger.info(f"{_pfx(self.pre)} Calling LAPACK eig solver")
        lam, vecs = eig(
            A.toarray(),
            B.toarray(),
            overwrite_a=True,
            overwrite_b=True,
            check_finite=False,
        )
        lam, vecs = filter_real_modes(lam, vecs, target_k0, 2, 2, sign=sign)
        return lam, vecs


############################################################
#                  ITERATIVE EIGEN SOLVERS                 #
############################################################


class SolverARPACK(EigSolver):
    """Optimized baseline ARPACK solver utilizing fast SuperLU shift-invert factorization."""

    name = "ARPACK"

    def __init__(self, pre: str):
        super().__init__(pre)
        self.pivoting_threshold: float = 0.001
        self.options: dict[str, str] = dict(
            SymmetricMode=True, Equil=False, IterRefine="SINGLE"
        )

    def eig(
        self,
        A: csc_matrix,
        B: csc_matrix,
        nmodes: int = 6,
        target_k0: float = 0,
        which: str = "LM",
        sign: float = 1.0,
    ) -> tuple[np.ndarray, np.ndarray]:
        n_total = A.shape[0]
        sigma = (sign * (target_k0**2)).real

        # Oversample subspace to bypass Maxwell nullspace modes
        k_request = min(max(nmodes * 3, 18), n_total - 2)
        ncv = min(max(4 * k_request, 50), n_total - 1)

        # 1. Fast, low-fill LU factorization at the fixed target shift
        A_shifted = (A - sigma * B).tocsc()
        lu = splu(
            A_shifted,
            permc_spec="MMD_AT_PLUS_A",
            relax=0,
            diag_pivot_thresh=self.pivoting_threshold,
            options=self.options,
        )

        def shift_invert_matvec(x: np.ndarray) -> np.ndarray:
            return lu.solve(B @ x)

        OPinv = LinearOperator(A.shape, matvec=shift_invert_matvec)

        # 2. Run ARPACK using the pre-factored shift operator
        evals_transformed, eigen_modes = eigs(
            OPinv,
            k=k_request,
            which=which,
            ncv=ncv,
            tol=1e-8,
        )

        # Map mapped eigenvalues back to real spectrum: lambda = sigma + 1/theta
        eigen_values = sigma + (1.0 / evals_transformed)

        # Sort solutions relative to closeness to target_k0
        k0_vals = np.sqrt(eigen_values / sign)
        sort_idx = np.argsort(np.abs(k0_vals.real - target_k0))[:nmodes]

        return eigen_values[sort_idx], eigen_modes[:, sort_idx]
